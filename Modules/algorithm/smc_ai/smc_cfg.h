/**
 * @file smc_cfg.h
 * @author ai (smc_ai)
 * @version V1.0.0
 * @date 2026/09/28
 * @brief 滑模控制(SMC)默认参数 (纯算法, 供 servo/roll 轴使用)
 *
 * @attention
 *  本头文件只放“可调参数的默认值”, 方便集中调参。所有量纲与调用方一致
 *  (本项目 roll 轴: 误差 e=roll 角(deg), e_dot=roll 角速率(deg/s), 输出 u 归一化 -1..1)。
 *  ⚠ 下列默认值仅为占位, **必须在地面/飞行现场整定**!
 */
#ifndef _SMC_CFG_H
#define _SMC_CFG_H

/* ----------------------------------------------------------------------------
 * 滑模面斜率 c (单位 1/s)
 *   滑模面 s = c*e + e_dot。c 越大越“看角度”, 越小越“看角速度”。
 *   典型 1 ~ 10。偏大响应快但易抖/超调; 偏小收敛慢。
 * -------------------------------------------------------------------------- */
#define SMC_DEFAULT_C (2.0f)

/* ----------------------------------------------------------------------------
 * 切换增益 k (输出量 / s 量纲)
 *   到达律 u = -k*sat(s/phi)。k 越大趋近越快、抗扰越强, 但过大易抖振。
 *   需与 max_out 配合(避免饱和)。现场整定。
 * -------------------------------------------------------------------------- */
#define SMC_DEFAULT_K (0.02f)

/* ----------------------------------------------------------------------------
 * 边界层厚度 phi (与 s 同量纲)
 *   sat(s/phi): |s|<phi 时线性(抑抖), 否则饱和到 ±1。phi 越大越平滑但越“软”。
 *   典型与 s 的期望幅值同量级。现场整定。
 * -------------------------------------------------------------------------- */
#define SMC_DEFAULT_PHI (50.0f)

/* ----------------------------------------------------------------------------
 * 输出限幅 max_out (>0): u 夹到 ±max_out。本项目输出归一化 => 默认 1.0。
 * -------------------------------------------------------------------------- */
#define SMC_DEFAULT_MAXOUT (1.0f)

#endif /* _SMC_CFG_H */
